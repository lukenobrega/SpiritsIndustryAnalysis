def pick_query_sheet(excel_path: Path) -> str:
    """Choose the main data sheet automatically."""
    xls = pd.ExcelFile(excel_path)
    for sheet in xls.sheet_names:
        if "query" in sheet.lower():
            return sheet
    return xls.sheet_names[0]


def load_iwsr_query(excel_path: Path):
    """
    Reads the IWSR export where the real header row starts with Country.
    Keeps Country, Category columns, Value columns, and Volume columns.
    """
    sheet_name = pick_query_sheet(excel_path)
    raw = pd.read_excel(excel_path, sheet_name=sheet_name, header=None)

    header_candidates = raw.index[
        raw.iloc[:, 0].astype(str).str.strip().eq("Country")
    ].tolist()

    if not header_candidates:
        raise ValueError("Could not find the header row starting with 'Country'.")

    header_row = header_candidates[0]
    headers = raw.iloc[header_row].tolist()

    main_cols = []
    for i, col in enumerate(headers):
        col_text = str(col)
        if (
            col_text in ["Country", "Category 1", "Category 2", "Category 3"]
            or re.match(r"^Value \d{4}$", col_text)
            or re.match(r"^Volume \d{4}$", col_text)
        ):
            main_cols.append(i)

    df = raw.iloc[header_row + 1 :, main_cols].copy()
    df.columns = [headers[i] for i in main_cols]

    df = df.dropna(how="all")
    df = df.dropna(
        subset=["Country", "Category 1", "Category 2", "Category 3"],
        how="all"
    )

    value_years = sorted([
        int(str(c).split()[1])
        for c in df.columns
        if re.match(r"^Value \d{4}$", str(c))
    ])

    volume_years = sorted([
        int(str(c).split()[1])
        for c in df.columns
        if re.match(r"^Volume \d{4}$", str(c))
    ])

    for year in value_years:
        df[f"Value {year}"] = pd.to_numeric(df[f"Value {year}"], errors="coerce")

    for year in volume_years:
        df[f"Volume {year}"] = pd.to_numeric(df[f"Volume {year}"], errors="coerce")

    return df, value_years, volume_years, sheet_name


def row_to_series(row: pd.Series, prefix: str, years: list[int]) -> pd.Series:
    """Turns Value 2014, Value 2015, etc. into a time series."""
    return pd.Series(
        {year: row[f"{prefix} {year}"] for year in years},
        dtype="float64"
    )


def calc_cagr(series: pd.Series, start_year: int, end_year: int) -> float:
    """CAGR from start_year to end_year."""
    start_value = series.loc[start_year]
    end_value = series.loc[end_year]
    n_years = end_year - start_year

    if pd.isna(start_value) or pd.isna(end_value):
        return np.nan

    if start_value <= 0 or n_years <= 0:
        return np.nan

    return (end_value / start_value) ** (1 / n_years) - 1


def rolling_5yr_cagr(series: pd.Series, end_years: list[int]) -> pd.Series:
    """Calculates 5-year CAGR ending in each year."""
    output = {}

    for end_year in end_years:
        start_year = end_year - 5

        if start_year in series.index and end_year in series.index:
            output[end_year] = calc_cagr(series, start_year, end_year)

    return pd.Series(output, dtype="float64")


def money_billions_formatter(x, pos):
    return f"{x:,.1f}"


def label_max_min_on_line(ax, series: pd.Series, scale: float = 1.0, value_suffix: str = ""):
    """Adds automatic max and min annotations to a line chart."""
    clean = series.dropna()

    if clean.empty:
        return

    max_year = int(clean.idxmax())
    min_year = int(clean.idxmin())

    max_value = clean.loc[max_year] / scale
    min_value = clean.loc[min_year] / scale

    ax.scatter([max_year], [max_value], zorder=5)
    ax.scatter([min_year], [min_value], zorder=5)

    ax.annotate(
        f"Max: {max_year}\n{max_value:,.1f}{value_suffix}",
        xy=(max_year, max_value),
        xytext=(10, 18),
        textcoords="offset points",
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )

    ax.annotate(
        f"Min: {min_year}\n{min_value:,.1f}{value_suffix}",
        xy=(min_year, min_value),
        xytext=(10, -32),
        textcoords="offset points",
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )


def label_selected_years_on_line(
    ax,
    series: pd.Series,
    years: list[int],
    scale: float = 1.0,
    value_suffix: str = ""
):
    """Labels specific years on a line chart."""
    offsets = {
        2019: (8, 10),
        2020: (8, -24),
        2021: (8, 10),
        2022: (8, -24),
        2023: (8, 10),
        2026: (8, -24),
        2030: (-58, 12),
    }

    for year in years:
        if year in series.index and pd.notna(series.loc[year]):
            value = series.loc[year] / scale
            xytext = offsets.get(year, (8, 10))

            ax.scatter([year], [value], zorder=4)

            ax.annotate(
                f"{year}\n{value:,.1f}{value_suffix}",
                xy=(year, value),
                xytext=xytext,
                textcoords="offset points",
                arrowprops={"arrowstyle": "-", "lw": 0.6},
            )


def label_max_min_on_bar(ax, x_values, y_values, percent: bool = False):
    """Adds automatic max and min annotations to a bar chart."""
    s = pd.Series(y_values, index=x_values).dropna()

    if s.empty:
        return

    max_x = s.idxmax()
    min_x = s.idxmin()

    max_y = s.max()
    min_y = s.min()

    for label, x, y in [("Max", max_x, max_y), ("Min", min_x, min_y)]:
        text_value = f"{y:.1%}" if percent else f"{y:,.1f}"

        ax.annotate(
            f"{label}: {x}\n{text_value}",
            xy=(x, y),
            xytext=(0, 18 if y >= 0 else -35),
            textcoords="offset points",
            ha="center",
            arrowprops={"arrowstyle": "->", "lw": 0.8},
        )


