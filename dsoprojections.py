def make_country_year_table(df, metric):
    """Creates a Country x Year pivot table."""
    country_year = (
        df.groupby(["Country", "Period"], as_index=False)[metric]
        .sum()
        .pivot(index="Country", columns="Period", values=metric)
        .sort_index()
    )

    return country_year


def make_top_bottom_change(series, n=10):
    """Keeps the largest gainers and largest decliners/smallest gainers."""
    selected = pd.concat([
        series.nsmallest(n),
        series.nlargest(n),
    ])

    selected = selected.drop_duplicates()
    selected = selected.sort_values()

    return selected


