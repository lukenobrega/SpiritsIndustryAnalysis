def pick_query_sheet(excel_path):
    """Chooses the Query sheet automatically."""
    xls = pd.ExcelFile(excel_path)

    for sheet in xls.sheet_names:
        if "query" in sheet.lower():
            return sheet

    return xls.sheet_names[0]


def load_iwsr_across_rows(excel_path):
    """
    Reads an IWSR Across Rows file.

    Expected columns:
    Period, Country, Category 1, Category 2, Category 3, Volume, Value
    """
    sheet_name = pick_query_sheet(excel_path)
    raw = pd.read_excel(excel_path, sheet_name=sheet_name, header=None)

    header_rows = raw.index[
        raw.iloc[:, 0].astype(str).str.strip().eq("Period")
    ].tolist()

    if not header_rows:
        raise ValueError("Could not find the header row starting with 'Period'.")

    header_row = header_rows[0]
    headers = [str(x).strip() for x in raw.iloc[header_row].tolist()]

    df = raw.iloc[header_row + 1:].copy()
    df.columns = headers

    expected_cols = [
        "Period",
        "Country",
        "Category 1",
        "Category 2",
        "Category 3",
        "Volume",
        "Value",
    ]

    missing_cols = [c for c in expected_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing expected columns: {missing_cols}")

    df = df[expected_cols].copy()

    df = df.dropna(how="all")
    df = df[df["Period"].notna() & df["Country"].notna()]

    df["Period"] = pd.to_numeric(df["Period"], errors="coerce")
    df["Volume"] = pd.to_numeric(df["Volume"], errors="coerce")
    df["Value"] = pd.to_numeric(df["Value"], errors="coerce")

    df = df.dropna(subset=["Period"])
    df["Period"] = df["Period"].astype(int)

    text_cols = ["Country", "Category 1", "Category 2", "Category 3"]
    for col in text_cols:
        df[col] = df[col].astype(str).str.strip()

    years = sorted(df["Period"].unique().tolist())

    return df, years, sheet_name


def calc_cagr(start_value, end_value, n_years):
    """Calculates CAGR."""
    if pd.isna(start_value) or pd.isna(end_value):
        return np.nan

    if start_value <= 0 or end_value <= 0 or n_years <= 0:
        return np.nan

    return (end_value / start_value) ** (1 / n_years) - 1


