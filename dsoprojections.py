def label_max_min_on_line(ax, series: pd.Series, scale: float = 1.0, value_suffix: str = ""):
    """Adds automatic max and min annotations to a line chart."""
    clean = series.dropna()

    if clean.empty:
        return

    max_year = int(clean.idxmax())
    min_year = int(clean.idxmin())

    max_value = clean.loc[max_year] / scale
    min_value = clean.loc[min_year] / scale

    ax.scatter([max_year], [max_value], zorder=5)
    ax.scatter([min_year], [min_value], zorder=5)

    ax.annotate(
        f"Max: {max_year}\n{max_value:,.1f}{value_suffix}",
        xy=(max_year, max_value),
        xytext=(10, 18),
        textcoords="offset points",
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )

    ax.annotate(
        f"Min: {min_year}\n{min_value:,.1f}{value_suffix}",
        xy=(min_year, min_value),
        xytext=(10, -32),
        textcoords="offset points",
        arrowprops={"arrowstyle": "->", "lw": 0.8},
    )


def label_selected_years_on_line(
    ax,
    series: pd.Series,
    years: list[int],
    scale: float = 1.0,
    value_suffix: str = ""
):
    """Labels specific years on a line chart."""
    offsets = {
        2019: (8, 10),
        2020: (8, -24),
        2021: (8, 10),
        2022: (8, -24),
        2023: (8, 10),
        2026: (8, -24),
        2030: (-58, 12),
    }

    for year in years:
        if year in series.index and pd.notna(series.loc[year]):
            value = series.loc[year] / scale
            xytext = offsets.get(year, (8, 10))

            ax.scatter([year], [value], zorder=4)

            ax.annotate(
                f"{year}\n{value:,.1f}{value_suffix}",
                xy=(year, value),
                xytext=xytext,
                textcoords="offset points",
                arrowprops={"arrowstyle": "-", "lw": 0.6},
            )


def label_max_min_on_bar(ax, x_values, y_values, percent: bool = False):
    """Adds automatic max and min annotations to a bar chart."""
    s = pd.Series(y_values, index=x_values).dropna()

    if s.empty:
        return

    max_x = s.idxmax()
    min_x = s.idxmin()

    max_y = s.max()
    min_y = s.min()

    for label, x, y in [("Max", max_x, max_y), ("Min", min_x, min_y)]:
        text_value = f"{y:.1%}" if percent else f"{y:,.1f}"

        ax.annotate(
            f"{label}: {x}\n{text_value}",
            xy=(x, y),
            xytext=(0, 18 if y >= 0 else -35),
            textcoords="offset points",
            ha="center",
            arrowprops={"arrowstyle": "->", "lw": 0.8},
        )


def label_category_trend_points(
    ax,
    series: pd.Series,
    category_index: int,
    color,
    selected_years: list[int],
    value_suffix: str = "B"
):
    """
    Labels min, max, and selected years on each category line.
    Designed for the Top US Spirits Category 2 Value Trends chart.
    """
    clean = series.dropna()

    if clean.empty:
        return

    min_year = int(clean.idxmin())
    max_year = int(clean.idxmax())

    years_to_label = sorted(set([min_year, max_year] + selected_years))

    # Rotating offsets
    min_offsets = [(-46, -26), (8, -28), (-50, 14), (8, 16), (-42, -10), (8, -16), (-48, 24)]
    max_offsets = [(8, 18), (-48, 18), (8, -28), (-50, -24), (8, 30), (-48, 30), (8, -16)]
    year_offsets = {
        2019: [(8, 12), (8, -26), (-48, 12), (-48, -26), (8, 24), (-48, 24), (8, -14)],
        2026: [(8, -28), (8, 14), (-50, -28), (-50, 14), (8, -40), (-50, -40), (8, 26)],
        2030: [(8, 0), (8, 10), (8, -10), (8, 20), (8, -20), (8, 30), (8, -30)],
    }

    for year in years_to_label:
        if year not in clean.index or pd.isna(clean.loc[year]):
            continue

        value = clean.loc[year]

        label_parts = []

        if year == min_year:
            label_parts.append(f"Min: {year}")

        if year == max_year:
            label_parts.append(f"Max: {year}")

#


        if year in selected_years and year not in [min_year, max_year]:
            label_parts.append(str(year))

        if not label_parts:
            continue

        label_text = " / ".join(label_parts) + f"\n{value:,.1f}{value_suffix}"

        if year == min_year:
            xytext = min_offsets[category_index % len(min_offsets)]
            arrowstyle = "->"
        elif year == max_year:
            xytext = max_offsets[category_index % len(max_offsets)]
            arrowstyle = "->"
        else:
            offsets_for_year = year_offsets.get(year, [(8, 10)])
            xytext = offsets_for_year[category_index % len(offsets_for_year)]
            arrowstyle = "-"

        ha = "left" if xytext[0] >= 0 else "right"

        ax.scatter(
            [year],
            [value],
            color=color,
            zorder=6,
            s=26,
        )

        ax.annotate(
            label_text,
            xy=(year, value),
            xytext=xytext,
            textcoords="offset points",
            ha=ha,
            va="center",
            fontsize=6.5,
            color=color,
            arrowprops={
                "arrowstyle": arrowstyle,
                "lw": 0.6,
                "color": color,
            },
        )


