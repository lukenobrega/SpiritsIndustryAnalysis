def find_excel_file():
    """Automatically finds the uploaded US Across Columns Excel file."""
    if MANUAL_FILE_PATH is not None:
        p = Path(MANUAL_FILE_PATH)
        if not p.exists():
            raise FileNotFoundError(f"Manual file path does not exist: {p}")
        return p

    search_roots = []

    if Path("/content").exists():
        search_roots.append(Path("/content"))

    search_roots.append(Path.cwd())

    if Path("/mnt/data").exists():
        search_roots.append(Path("/mnt/data"))

    candidates = []
    for root in search_roots:
        candidates.extend(root.glob("*.xlsx"))

    # Prefer the exact US Across Columns file.
    preferred = [
        p for p in candidates
        if "US - Across Columns" in p.name and p.name.lower().endswith(".xlsx")
    ]

    if preferred:
        return preferred[0]

    # Fallback: any file that looks like the IWSR forecasting file but not global.
    fallback = [
        p for p in candidates
        if "IWSR" in p.name and "Across Columns" in p.name and "Global" not in p.name
    ]

    if fallback:
        return fallback[0]

    raise FileNotFoundError(
        "Could not find the US Across Columns Excel file. Upload it to Colab, "
        "or set MANUAL_FILE_PATH at the top of the code."
    )


def pick_query_sheet(excel_path):
    """Chooses the Query sheet automatically."""
    xls = pd.ExcelFile(excel_path)
    for sheet in xls.sheet_names:
        if "query" in sheet.lower():
            return sheet
    return xls.sheet_names[0]


def load_iwsr_across_columns(excel_path):
    """Reads an IWSR Across Columns export where the header row starts with Country."""
    sheet_name = pick_query_sheet(excel_path)
    raw = pd.read_excel(excel_path, sheet_name=sheet_name, header=None)

    header_rows = raw.index[
        raw.iloc[:, 0].astype(str).str.strip().eq("Country")
    ].tolist()

    if not header_rows:
        raise ValueError("Could not find the header row starting with 'Country'.")

    header_row = header_rows[0]
    headers = raw.iloc[header_row].tolist()

    keep_cols = []
    for i, col in enumerate(headers):
        col_text = str(col).strip()
        if (
            col_text in ["Country", "Category 1", "Category 2", "Category 3"]
            or re.match(r"^Value \d{4}$", col_text)
            or re.match(r"^Volume \d{4}$", col_text)
        ):
            keep_cols.append(i)

    df = raw.iloc[header_row + 1 :, keep_cols].copy()
    df.columns = [str(headers[i]).strip() for i in keep_cols]

    df = df.dropna(how="all")
    df = df.dropna(
        subset=["Country", "Category 1", "Category 2", "Category 3"],
        how="all"
    )

    value_years = sorted([
        int(str(c).split()[1])
        for c in df.columns
        if re.match(r"^Value \d{4}$", str(c))
    ])

    volume_years = sorted([
        int(str(c).split()[1])
        for c in df.columns
        if re.match(r"^Volume \d{4}$", str(c))
    ])

    for year in value_years:
        df[f"Value {year}"] = pd.to_numeric(df[f"Value {year}"], errors="coerce")

    for year in volume_years:
        df[f"Volume {year}"] = pd.to_numeric(df[f"Volume {year}"], errors="coerce")

    return df, value_years, volume_years, sheet_name


def row_to_series(row, prefix, years):
    """Converts Value 2018, Value 2019, etc. into a clean pandas Series."""
    return pd.Series(
        {year: row[f"{prefix} {year}"] for year in years},
        dtype="float64"
    )


def calc_cagr(series, start_year, end_year):
    """Calculates CAGR from start_year to end_year."""
    if start_year not in series.index or end_year not in series.index:
        return np.nan

    start_value = series.loc[start_year]
    end_value = series.loc[end_year]
    n_years = end_year - start_year

    if pd.isna(start_value) or pd.isna(end_value):
        return np.nan
    if start_value <= 0 or end_value <= 0 or n_years <= 0:
        return np.nan

    return (end_value / start_value) ** (1 / n_years) - 1


